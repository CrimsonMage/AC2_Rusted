/// The DB type DID `did` belongs to, if any range holds it.
pub fn db_type(did: u32) -> Option<u32> {
    RANGES
        .iter()
        .find(|(first, last, _)| (*first..=*last).contains(&did))
        .map(|r| r.2)
}

