/// The 7160/7230 efun id of an efun id of a library of the 0930 release (`release_0930`), or
/// the id itself for the other libraries.
pub(crate) fn efun_from_release(release_0930: bool, efun: u32) -> u32 {
    if !release_0930 {
        return efun;
    }
    if let Ok(at) = MOVED.binary_search_by_key(&efun, |(release, _)| *release) {
        return MOVED[at].1;
    }
    ac2_core::native_type_from_release(efun >> 16) << 16 | (efun & 0xFFFF)
}

/// The 7160/7230 native type id of a type id in a library's bytecode (`NewNative`).
pub(crate) fn native_type_from_release(release_0930: bool, native_type: u32) -> u32 {
    if release_0930 {
        ac2_core::native_type_from_release(native_type)
    } else {
        native_type
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_and_names_no_efun_twice() {
        assert!(MOVED.windows(2).all(|w| w[0].0 < w[1].0));
        let mut targets: Vec<u32> = MOVED
            .iter()
            .map(|(_, t)| *t)
            .filter(|t| *t != UNBOUND)
            .collect();
        targets.sort_unstable();
        assert!(targets.windows(2).all(|w| w[0] < w[1]));
    }
}
